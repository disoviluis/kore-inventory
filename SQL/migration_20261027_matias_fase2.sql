-- MATIAS FASE 2 - Documentos fiscales de ventas
-- Ejecutar manualmente. No activa emisiones automaticas ni modifica ventas existentes.

CREATE TABLE IF NOT EXISTS matias_documentos (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  empresa_id INT NOT NULL,
  venta_id INT NOT NULL,
  entorno ENUM('sandbox','produccion') NOT NULL DEFAULT 'sandbox',
  tipo_documento_id INT NOT NULL DEFAULT 1,
  tipo_operacion_id INT NOT NULL DEFAULT 1,
  request_uuid VARCHAR(36) NOT NULL,
  matias_uuid VARCHAR(36) NULL,
  document_number VARCHAR(100) NULL,
  cufe VARCHAR(256) NULL,
  zip_key VARCHAR(100) NULL,
  xml_name VARCHAR(255) NULL,
  pdf_path VARCHAR(500) NULL,
  qr_url VARCHAR(500) NULL,
  estado ENUM('created','emitting','emitted','accepted','rejected','voided','unknown') NOT NULL DEFAULT 'created',
  dian_status_code VARCHAR(20) NULL,
  dian_status_description VARCHAR(255) NULL,
  dian_is_valid VARCHAR(10) NULL,
  payload_hash CHAR(64) NOT NULL,
  request_payload JSON NULL,
  response_payload JSON NULL,
  warning_payload JSON NULL,
  error_payload JSON NULL,
  provider_reference VARCHAR(100) NULL,
  attempt_count INT UNSIGNED NOT NULL DEFAULT 0,
  last_attempt_at DATETIME NULL,
  accepted_at DATETIME NULL,
  rejected_at DATETIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  created_by INT NULL,
  PRIMARY KEY (id),
  UNIQUE KEY uk_matias_documento_venta_entorno (empresa_id, venta_id, entorno, tipo_documento_id),
  UNIQUE KEY uk_matias_documento_request_uuid (request_uuid),
  KEY idx_matias_documento_company_uuid (matias_uuid),
  KEY idx_matias_documento_cufe (cufe),
  KEY idx_matias_documento_estado (empresa_id, entorno, estado),
  CONSTRAINT fk_matias_documento_empresa FOREIGN KEY (empresa_id) REFERENCES empresas(id) ON DELETE CASCADE,
  CONSTRAINT fk_matias_documento_venta FOREIGN KEY (venta_id) REFERENCES ventas(id) ON DELETE CASCADE,
  CONSTRAINT fk_matias_documento_usuario FOREIGN KEY (created_by) REFERENCES usuarios(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS matias_documento_intentos (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  documento_id BIGINT UNSIGNED NOT NULL,
  empresa_id INT NOT NULL,
  numero_intento INT UNSIGNED NOT NULL,
  request_hash CHAR(64) NOT NULL,
  http_status INT NULL,
  provider_code VARCHAR(100) NULL,
  provider_message TEXT NULL,
  success TINYINT(1) NULL,
  response_payload JSON NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uk_matias_documento_intento (documento_id, numero_intento),
  KEY idx_matias_intento_empresa (empresa_id, created_at),
  CONSTRAINT fk_matias_intento_documento FOREIGN KEY (documento_id) REFERENCES matias_documentos(id) ON DELETE CASCADE,
  CONSTRAINT fk_matias_intento_empresa FOREIGN KEY (empresa_id) REFERENCES empresas(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
